void send_data(void)
{
    char header[100];
    HAL_StatusTypeDef status;

    snprintf(header, sizeof(header), "START,%lu,%lu\n",
             (uint32_t)SAMPLE_COUNT, loop_cycles);
    status = HAL_UART_Transmit(&huart3, (uint8_t *)header, strlen(header), HAL_MAX_DELAY);
    
    if (status != HAL_OK) {
        // Blink red LED if transmission fails
        HAL_GPIO_WritePin(ONBOARD_LED_RED_GPIO_Port, ONBOARD_LED_RED_Pin, GPIO_PIN_SET);
        HAL_Delay(2000);
        HAL_GPIO_WritePin(ONBOARD_LED_RED_GPIO_Port, ONBOARD_LED_RED_Pin, GPIO_PIN_RESET);
    }
    
    status = HAL_UART_Transmit(&huart3, (uint8_t *)"END\r\n", 5, HAL_MAX_DELAY);
}

